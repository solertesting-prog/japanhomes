function build(spec: DemoSpec): PropertyRecord {
  const capital =
    spec.financials.purchasePrice + spec.financials.acquisitionCosts + spec.financials.renovationCosts + spec.financials.reserves;
  if (capital % spec.tokenPrice !== 0n) {
    throw new Error(`DEMO fixture ${spec.slug}: capital ¥${capital} not divisible by token price ¥${spec.tokenPrice}`);
  }
  const totalTokens = capital / spec.tokenPrice;
  const financials: OfferingFinancials = { ...spec.financials, totalTokens };
  const tokensSold =
    spec.fundingStatus === 'FUNDED' ? totalTokens : (totalTokens * BigInt(spec.tokensSoldBps)) / 10_000n;
  const metrics = computeOfferingMetrics(financials);

  // Quarterly DEMO distributions: whole yen per token, total = perToken × supply.
  const distributions: PropertyRecord['distributions'] = [];
  const quarterly = metrics.estimatedDistributable > 0n ? metrics.estimatedDistributable / 4n : 0n;
  const perToken = quarterly / totalTokens;
  for (let q = 0; q < spec.distributionQuarters; q++) {
    // Quarters ending 30 Sep 2026 and earlier, paid ~25 days after quarter end.
    const end = new Date(Date.UTC(2026, 9 - q * 3, 0)); // last day of Sep, Jun, Mar…
    const start = new Date(Date.UTC(end.getUTCFullYear(), end.getUTCMonth() - 2, 1));
    const paid = new Date(Date.UTC(end.getUTCFullYear(), end.getUTCMonth() + 1, 25));
    // Slight variation so the history does not look synthetic-flat; still exact per token.
    const variation = BigInt(100 - (q % 3) * 4);
    const pt = (perToken * variation) / 100n;
    distributions.push({
      id: distId(spec.n, q + 1),
      periodStart: start,
      periodEnd: end,
      paidAt: paid,
      totalAmount: pt * totalTokens,
      amountPerToken: pt,
    });
  }

  const appraised = (spec.financials.purchasePrice * BigInt(10_000 + spec.appraisalDeltaBps)) / 10_000n;

  return {
    id: demoId(spec.n),
    slug: spec.slug,
    isDemo: true,
    name: spec.name,
    city: spec.city,
    prefecture: CITY_PREFECTURE[spec.city],
    neighborhood: spec.neighborhood,
    approximateAddress: spec.approximateAddress,
    latitude: spec.latitude,
    longitude: spec.longitude,
    type: spec.type,
    layout: spec.layout,
    structure: spec.structure,
    floorAreaM2: spec.floorAreaM2,
    landAreaM2: spec.landAreaM2,
    yearBuilt: spec.yearBuilt,
    nearestStation: spec.nearestStation,
    walkMinutes: spec.walkMinutes,
    condition: spec.condition,
    rentalStatus: spec.rentalStatus,
    summary: spec.summary,
    description: spec.description,
    highlights: spec.highlights,
    risks: [...spec.risks, ...COMMON_RISKS],
    fundingStatus: spec.fundingStatus,
    featured: spec.featured,
    publishedAt: new Date(spec.publishedAt),
    financials,
    tokensSold,
    minimumInvestment: spec.minimumInvestment,
    maximumInvestment: spec.maximumInvestment,
    legalStructure: spec.legalStructure,
    token: {
      name: `JPT ${spec.name} (DEMO)`,
      symbol: spec.symbol,
      network: 'EVM testnet — not deployed',
      chainId: null,
      contractAddress: null,
      standard: 'ERC-3643 permissioned token (planned)',
      economicRights: `${STRUCTURE_LABEL[spec.legalStructure]}: pro-rata share of distributable rental income and of net sale proceeds. No title to the building.`,
      transferRestrictions:
        'Transfers only between wallets of KYC-approved, eligible investors, subject to lock-up and issuer approval. Secondary trading disabled.',
    },
    roundOpensAt: spec.roundOpensAt ? new Date(spec.roundOpensAt) : null,
    roundClosesAt: spec.roundClosesAt ? new Date(spec.roundClosesAt) : null,
    valuation: {
      appraisedValue: appraised,
      appraisedAt: new Date(spec.appraisedAt),
      method: 'Income capitalisation and comparable sales (DEMO)',
      appraiser: 'Fictional Appraisal Partners K.K. (DEMO)',
    },
    documents: documentsFor(spec.n),
    distributions,
  };
}

